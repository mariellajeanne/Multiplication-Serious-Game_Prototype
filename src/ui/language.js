/* Render-time pass: Tagalog mode rewrites matching text nodes and accessible
 * attributes as they render, remembering each English original so switching back
 * restores them. Names, numbers and anything not in the tables stay untouched. */
const PANADERYA_LOCALIZED_ATTRIBUTES=['aria-label','title','placeholder','alt','aria-valuetext'];
const panaderyaTextOriginals=new WeakMap(),panaderyaAttributeOriginals=new WeakMap();
let panaderyaLocalizer=null;
function localizedDisplayValue(value){
 if(!value||!/[A-Za-z]{2}/.test(value))return null;
 const core=value.replace(/\s+/g,' ').trim(),translated=tagalogFor(core);
 if(translated==null||translated===core)return null;
 return /^\s*/.exec(value)[0]+translated+/\s*$/.exec(value)[0];
}
function localizationSkipped(element){return !element||!!element.closest('script,style,textarea,[translate="no"]')}
function localizeTextNode(node){
 const record=panaderyaTextOriginals.get(node);
 if(record&&node.nodeValue===record.tl)return;
 if(localizationSkipped(node.parentElement))return;
 const tl=localizedDisplayValue(node.nodeValue);
 if(tl==null){panaderyaTextOriginals.delete(node);return}
 panaderyaTextOriginals.set(node,{en:node.nodeValue,tl});
 node.nodeValue=tl;
}
function localizeAttributes(element){
 let records=panaderyaAttributeOriginals.get(element);
 for(const name of PANADERYA_LOCALIZED_ATTRIBUTES){
  if(!element.hasAttribute(name))continue;
  const value=element.getAttribute(name),record=records?.[name];
  if(record&&value===record.tl)continue;
  const tl=localizedDisplayValue(value);
  if(tl==null){if(record)delete records[name];continue}
  if(!records){records={};panaderyaAttributeOriginals.set(element,records)}
  records[name]={en:value,tl};
  element.setAttribute(name,tl);
 }
}
function walkLocalizable(root,onText,onElement){
 if(!root)return;
 if(root.nodeType===3){onText(root);return}
 if(root.nodeType!==1&&root.nodeType!==11)return;
 if(root.nodeType===1){if(root.closest('script,style'))return;onElement(root)}
 const walker=root.ownerDocument.createTreeWalker(root,5);// SHOW_ELEMENT | SHOW_TEXT
 for(let node=walker.nextNode();node;node=walker.nextNode())node.nodeType===3?onText(node):onElement(node);
}
function localizeTree(root){walkLocalizable(root,localizeTextNode,element=>{if(!localizationSkipped(element))localizeAttributes(element)})}
function restoreEnglishTree(root){
 walkLocalizable(root,node=>{const record=panaderyaTextOriginals.get(node);if(record&&node.nodeValue===record.tl)node.nodeValue=record.en;panaderyaTextOriginals.delete(node)},element=>{
  const records=panaderyaAttributeOriginals.get(element);if(!records)return;
  for(const [name,record] of Object.entries(records))if(element.getAttribute(name)===record.tl)element.setAttribute(name,record.en);
  panaderyaAttributeOriginals.delete(element);
 });
}
function syncPageLanguage(){
 if(typeof document==='undefined'||typeof MutationObserver!=='function')return;
 if(!document.body){if(typeof document.addEventListener==='function')document.addEventListener('DOMContentLoaded',syncPageLanguage,{once:true});return}
 if(panaderyaLanguage==='tl'){
  if(!panaderyaLocalizer)panaderyaLocalizer=new MutationObserver(records=>{for(const record of records){
   if(record.type==='characterData')localizeTextNode(record.target);
   else if(record.type==='attributes'){if(!localizationSkipped(record.target))localizeAttributes(record.target)}
   else for(const node of record.addedNodes)localizeTree(node);
  }});
  panaderyaLocalizer.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:PANADERYA_LOCALIZED_ATTRIBUTES});
  localizeTree(document.body);
 }else if(panaderyaLocalizer){panaderyaLocalizer.disconnect();panaderyaLocalizer=null;restoreEnglishTree(document.body)}
}
syncPageLanguage();
// The worksheet iframes share this storage; follow a change made in the parent page.
if(typeof window!=='undefined'&&typeof window.addEventListener==='function')window.addEventListener('storage',event=>{
 if(event.key!==PANADERYA_LANGUAGE_KEY)return;
 panaderyaLanguage=event.newValue==='tl'?'tl':'en';
 if(typeof document!=='undefined')document.documentElement.lang=panaderyaLanguage;
 syncPageLanguage();
});
