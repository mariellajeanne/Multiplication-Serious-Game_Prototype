"""Shared steps for browser runners written before the three-page scene UI.

The current production bakery has no `.hub-food`/`.hub-ticket` home screen, a fresh
profile starts the six-task tutorial, and products are generated by tapping the
floating expression bubble inside the worksheet (no shell Generate button).
"""

def ready(page, skip_tutorial=True):
    """Wait for the loaded scene; dismiss the first-run tutorial (it gates input)."""
    page.wait_for_function("document.getElementById('bakeryLoading')?.hidden&&typeof navigateBakery==='function'", timeout=30000)
    page.wait_for_timeout(250)
    if skip_tutorial:
        page.evaluate('window.skipWholeBakeryGuide?.()')


def open_ticket(page, tap=False):
    """Open the first enabled order ticket through the real Orders scene."""
    page.evaluate("if(typeof closeModal==='function'&&typeof modal!=='undefined'&&modal)closeModal();navigateBakery('orders')")
    page.wait_for_function("!bakeryJourney&&bakeryPage==='orders'", timeout=30000)
    ticket = page.locator('.scene-ticket:not(:disabled)').first
    ticket.wait_for(state='visible')
    ticket.tap() if tap else ticket.click()
    page.wait_for_function('document.querySelector("#worksheetFrame")?.worksheetStarted===true', timeout=30000)


def frame(page):
    return page.locator('#worksheetFrame').element_handle().content_frame()


def generate(page, tap=False):
    """Tap the expression bubble; take the normal 'auto' generation if Golden is offered."""
    f = frame(page)
    bubble = f.locator('#equationReveal')
    bubble.wait_for(state='visible')
    bubble.tap() if tap else bubble.click()
    page.wait_for_timeout(200)
    for root in (page, f):
        option = root.locator('[data-golden-option="auto"]')
        if option.count():
            option.first.tap() if tap else option.first.click()
            break
    page.wait_for_function('document.querySelector("#worksheetFrame").contentWindow.eval("s.revealed")', timeout=30000)
